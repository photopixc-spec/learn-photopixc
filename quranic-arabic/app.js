  function getRoute() {
    var h = (window.location.hash || '#qa-home').replace(/^#/, '');
    if (h.indexOf('qa-') === 0) h = h.slice(3);
    return h || 'home';
  }

  function render() {
    var route = getRoute();
    var view = document.getElementById('view');
    if (!view) return;

    document.documentElement.setAttribute('data-age-mode', state.ageMode || 'kids');

    var navKey = route.indexOf('word-') === 0 ? 'words' : route;
    var links = document.querySelectorAll('[data-route]');
    for (var i = 0; i < links.length; i++) {
      var r = links[i].getAttribute('data-route');
      links[i].classList.toggle('active', r === navKey);
    }

    if (route.indexOf('word-') === 0) {
      view.innerHTML = renderWordDetail(route.slice(5));
    } else if (route === 'path') {
      view.innerHTML = renderPath();
    } else if (route === 'alphabet') {
      view.innerHTML = renderAlphabet();
    } else if (route === 'harakat') {
      view.innerHTML = renderHarakat();
    } else if (route === 'builder') {
      view.innerHTML = renderBuilder();
    } else if (route === 'words') {
      view.innerHTML = renderWords();
    } else if (route === 'kids' || route === 'quiz' || route === 'daily') {
      view.innerHTML = renderKids();
    } else if (route === 'flashcards') {
      view.innerHTML = renderFlashcards();
    } else if (route === 'last-ten') {
      view.innerHTML = renderLastTen();
    } else if (route === 'salah') {
      view.innerHTML = renderSalah();
    } else if (route === 'progress' || route === 'about') {
      view.innerHTML = renderProgress();
    } else {
      view.innerHTML = renderHome();
    }

    if (route === 'alphabet' && V4.bindTracingCanvas) {
      V4.bindTracingCanvas();
    }
    bindViewEvents();
    updateBadges();
  }

